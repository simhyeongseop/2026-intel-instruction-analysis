"""Capture an isolated before/after validation snapshot for the R0-P0 work.

Run from the repository root on Ubuntu:
  python3 scripts/run_spec_probe.py --phase before
  python3 scripts/run_spec_probe.py --phase after --baseline out/spec_probe/<BEFORE_UTC>

The probe never executes generated instruction bytes.  All commands run in a
copied workspace and all new results stay below one out/spec_probe directory.
"""

from __future__ import annotations

import argparse
from collections import Counter
import csv
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
PROBE_ROOT = ROOT / "out/spec_probe"
PROTECTED = ("out/lint", "out/review", "out/ubuntu-tests")
SNAPSHOT_DIRS = ("pipeline", "scripts", "tests", "docs/review_artifacts", "data/db")
SNAPSHOT_FILES = (
    "data/cases.csv", "out/asm_result.csv", "out/roundtrip.csv", "out/triage.csv",
    "out/triage_report.md", "out/tests.s", "out/generator_skipped.csv",
    "out/lint/results.csv", "out/lint/manifest.json",
    "out/lint/report.md", "CLAUDE.md", "README.md", "spec.md",
)


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def tree_hashes(root: Path, names) -> dict[str, str]:
    result = {}
    for name in names:
        path = root / name
        if path.is_file():
            result[name] = file_sha256(path)
        elif path.is_dir():
            for child in sorted(item for item in path.rglob("*") if item.is_file()):
                relative = child.relative_to(root).as_posix()
                result[relative] = file_sha256(child)
    return result


def changed_hashes(before, after):
    return sorted(name for name in set(before) | set(after) if before.get(name) != after.get(name))


def copy_workspace(destination: Path):
    destination.mkdir(parents=True)
    copied = []
    for name in SNAPSHOT_DIRS:
        source = ROOT / name
        if not source.is_dir():
            continue
        for path in sorted(item for item in source.rglob("*") if item.is_file()):
            if "__pycache__" in path.parts or path.suffix in {".pyc", ".o"}:
                continue
            relative = path.relative_to(ROOT)
            target = destination / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
            copied.append(relative.as_posix())
    for name in SNAPSHOT_FILES:
        source = ROOT / name
        if not source.is_file():
            continue
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        copied.append(name)
    return sorted(set(copied))


def read_csv(path: Path):
    if not path.is_file():
        return []
    with path.open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def saved_data_audit(workspace: Path):
    db = read_csv(workspace / "data/db/isa_db.csv")
    tokens = read_csv(workspace / "data/db/tokens.csv")
    combos = read_csv(workspace / "data/db/combos.csv")
    assembly = read_csv(workspace / "out/asm_result.csv")
    lint = read_csv(workspace / "out/lint/results.csv")
    triage = read_csv(workspace / "out/triage.csv")
    return {
        "scope": "saved-data baseline; no generated bytes executed",
        "counts": {
            "db_rows": len(db), "token_rows": len(tokens), "combo_rows": len(combos),
            "assembly_rows": len(assembly), "lint_rows": len(lint), "triage_rows": len(triage),
            "lint_status": dict(Counter(row.get("status", "") for row in lint)),
            "lint_opcode_fields": dict(Counter(row.get("opcode_fields", "") for row in lint)),
            "triage_verdict": dict(Counter(row.get("verdict", "") for row in triage)),
        },
        "r0_columns_present": bool(tokens) and {
            "raw_operand_token", "normalized_operand_token", "validation_status", "validation_codes"
        } <= set(tokens[0]),
        "file_hashes": tree_hashes(workspace, SNAPSHOT_FILES + ("data/db",)),
    }


def run_command(command, cwd: Path, output_prefix: Path, temp_dir: Path, extra_env=None):
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1", PYTHONIOENCODING="utf-8",
               TMPDIR=str(temp_dir), TMP=str(temp_dir), TEMP=str(temp_dir))
    env.update(extra_env or {})
    process = subprocess.run(command, cwd=cwd, capture_output=True, text=True,
                             encoding="utf-8", errors="replace", env=env)
    output_prefix.parent.mkdir(parents=True, exist_ok=True)
    output_prefix.with_suffix(".stdout.txt").write_text(process.stdout, encoding="utf-8")
    output_prefix.with_suffix(".stderr.txt").write_text(process.stderr, encoding="utf-8")
    return {"command": command, "returncode": process.returncode,
            "stdout": str(output_prefix.with_suffix('.stdout.txt')),
            "stderr": str(output_prefix.with_suffix('.stderr.txt'))}


def resolve_baseline(value: str) -> Path:
    path = (ROOT / value).resolve() if not Path(value).is_absolute() else Path(value).resolve()
    probe_root = PROBE_ROOT.resolve()
    if path == probe_root or probe_root not in path.parents:
        raise ValueError("baseline must be a run directory below out/spec_probe")
    if not (path / "before/audit.json").is_file():
        raise ValueError("baseline does not contain before/audit.json")
    return path


def build_delta(before_rows, after_rows):
    before = {row.get("case_id", ""): row for row in before_rows}
    after = {row.get("case_id", ""): row for row in after_rows}
    delta = []
    fields = ("status", "validation_status", "as_bytes", "clang_bytes",
              "opcode_fields", "encoding_target_match")
    for case_id in sorted(set(before) | set(after)):
        old, new = before.get(case_id, {}), after.get(case_id, {})
        changes = {field: [old.get(field, ""), new.get(field, "")]
                   for field in fields if old.get(field, "") != new.get(field, "")}
        if changes or not old or not new:
            delta.append({"case_id": case_id,
                          "lineage_status": "matched" if old and new else "unmatched",
                          "changes": changes})
    return delta


def write_delta(run_dir: Path, baseline: Path, after_rows):
    before_rows = read_csv(baseline / "before/workspace/out/lint/results.csv")
    delta = build_delta(before_rows, after_rows)
    (run_dir / "delta.json").write_text(json.dumps(delta, ensure_ascii=False, indent=2) + "\n",
                                         encoding="utf-8")
    with (run_dir / "delta.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=("case_id", "lineage_status", "changes"))
        writer.writeheader()
        for row in delta:
            writer.writerow(dict(row, changes=json.dumps(row["changes"], ensure_ascii=False, sort_keys=True)))
    return {"before_rows": len(before_rows), "after_rows": len(after_rows),
            "changed_or_unmatched": len(delta)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--phase", choices=("before", "after"), required=True)
    parser.add_argument("--baseline", help="before run directory; required for --phase after")
    args = parser.parse_args(argv)
    if args.phase == "after" and not args.baseline:
        parser.error("--phase after requires --baseline")
    if args.phase == "before" and args.baseline:
        parser.error("--baseline is only valid for --phase after")

    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    run_dir = PROBE_ROOT / stamp
    if run_dir.exists():
        raise SystemExit(f"probe directory already exists: {run_dir}")
    phase_dir = run_dir / args.phase
    workspace = phase_dir / "workspace"
    temp_dir = run_dir / "tmp"
    temp_dir.mkdir(parents=True)
    protected_before = tree_hashes(ROOT, PROTECTED)
    copied = copy_workspace(workspace)
    git_head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                              text=True, encoding="utf-8", errors="replace").stdout.strip()
    manifest = {
        "schema_version": 1, "phase": args.phase, "created_utc": datetime.now(timezone.utc).isoformat(),
        "git_head": git_head, "source_root": str(ROOT), "run_dir": str(run_dir),
        "baseline": str(resolve_baseline(args.baseline)) if args.baseline else None,
        "copied_files": copied, "commands": [], "completed": False,
        "executes_generated_bytes": False,
    }

    audit = saved_data_audit(workspace)
    (phase_dir / "audit.json").write_text(json.dumps(audit, ensure_ascii=False, indent=2) + "\n",
                                           encoding="utf-8")
    failed = False
    if args.phase == "after":
        pipeline = run_command([sys.executable, "pipeline/run.py", "assembler", "--until",
                                "reassemble_check"], workspace, phase_dir / "pipeline", temp_dir)
        manifest["commands"].append(pipeline)
        failed = pipeline["returncode"] != 0

    if not failed:
        tests = run_command([sys.executable, "-m", "unittest", "discover", "-s", "tests",
                             "-p", "test_*.py", "-v"], workspace, phase_dir / "tests", temp_dir)
        manifest["commands"].append(tests)
        failed = tests["returncode"] != 0

    if args.phase == "after" and not failed:
        lint_dir = phase_dir / "intel"
        lint = run_command([sys.executable, "pipeline/m13_lint.py", "--output-dir", str(lint_dir)],
                           workspace, phase_dir / "lint", temp_dir)
        manifest["commands"].append(lint)
        failed = lint["returncode"] != 0
        if (lint_dir / "results.csv").is_file():
            manifest["delta"] = write_delta(run_dir, resolve_baseline(args.baseline),
                                             read_csv(lint_dir / "results.csv"))
        audit["post_pipeline"] = saved_data_audit(workspace)
        (phase_dir / "audit.json").write_text(json.dumps(audit, ensure_ascii=False, indent=2) + "\n",
                                               encoding="utf-8")

    protected_after = tree_hashes(ROOT, PROTECTED)
    protection = {"protected_paths": list(PROTECTED),
                  "changed_files": changed_hashes(protected_before, protected_after)}
    (run_dir / "protection.json").write_text(json.dumps(protection, ensure_ascii=False, indent=2) + "\n",
                                              encoding="utf-8")
    failed = failed or bool(protection["changed_files"])
    manifest.update(completed=not failed, finished_utc=datetime.now(timezone.utc).isoformat())
    (run_dir / "run_manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
                                                encoding="utf-8")
    print(json.dumps({"run_dir": str(run_dir), "phase": args.phase,
                      "completed": manifest["completed"],
                      "protected_changes": protection["changed_files"],
                      "counts": audit["counts"]}, ensure_ascii=False, indent=2))
    return 0 if manifest["completed"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
